#!/usr/bin/env python3
"""Generate guest-only ASCII coverage masks; requires Pillow 11.3.0, not at build/run."""
from pathlib import Path
import subprocess
from PIL import Image, ImageDraw, ImageFont
ROOT = Path(__file__).resolve().parents[1]
font_path = ROOT / 'assets/fonts/Ubuntu-Light.ttf'
data = bytearray()
rows = []
for size in [14, 20, 46]:
    font = ImageFont.truetype(str(font_path), size)
    for code in range(32, 127):
        ch = chr(code)
        left, top, right, bottom = font.getbbox(ch)
        width, height = right-left, bottom-top
        image = Image.new('L', (width, height))
        ImageDraw.Draw(image).text((-left, -top), ch, font=font, fill=255)
        rows.append(f'    Glyph {{ offset: {len(data)}, width: {width}, height: {height}, left: {left}, top: {top}, advance: {round(font.getlength(ch))} }},')
        data.extend(image.tobytes())
packed = bytes(((data[i] + 8) // 17 << 4) | ((data[i+1] + 8) // 17 if i+1 < len(data) else 0) for i in range(0, len(data), 2))
(ROOT / 'assets/fonts/rai-ascii.bin').write_bytes(packed)
(ROOT / 'src/display/glyphs.rs').write_text('// Generated by scripts/generate_display_font.py. Ubuntu-derived glyph masks: UFL-1.0.\nuse super::font::Glyph;\npub static GLYPHS: [Glyph; 285] = [\n'+'\n'.join(rows)+'\n];\n')
subprocess.run(['rustfmt', '--edition', '2024', str(ROOT / 'src/display/glyphs.rs')], check=True)
print(f'Generated {len(packed)} bytes of 4-bit glyph coverage at 14, 20 and 46 pixels')
