//! Host filesystem publication. This module does not execute these files in QEMU.
use crate::{config, decision_source, mission, provider, semantic::Request};
use serde_json::json;
use std::{fs, path::Path, process::Command, time::Instant};
fn request(path: &Path) -> Result<Request, String> {
    Ok(Request::parse(&config::bounded_file(path, 4096)?)?)
}
pub fn plan(path: &Path, replay: Option<&Path>) -> Result<(), String> {
    let r = request(path)?;
    let start = Instant::now();
    println!(
        "{}",
        json!({"event":"mission_started","source":if replay.is_some(){"replay"}else{"meta"},"request":r,"execution_location":"host","catalog_version":1,"permissions_version":1})
    );
    let p = if let Some(path) = replay {
        mission::parse(&config::bounded_file(path, 8192)?)?
    } else {
        let key = config::load()?;
        let answer =
            decision_source::report(provider::mission(&key, &r), u64::from(r.request_version))?;
        println!(
            "{}",
            json!({"event":"mission_response","latency_ms":answer.latency_ms,"usage":answer.usage})
        );
        answer.proposal
    };
    mission::validate(&p, &r)?;
    println!(
        "{}",
        json!({"event":"mission_plan","plan":p,"elapsed_ms":start.elapsed().as_millis(),"validation":"authority_and_literal_quotes_not_intent"})
    );
    Ok(())
}
fn escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&#39;")
}
