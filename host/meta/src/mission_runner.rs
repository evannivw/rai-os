pub fn build(request_path: &Path, plan_path: &Path, output: &Path) -> Result<(), String> {
    let r = request(request_path)?;
    let p = mission::parse(&config::bounded_file(plan_path, 8192)?)?;
    mission::validate(&p, &r)?;
    if p.decision != "publish" {
        return Err("mission_not_publishable".into());
    }
    // Require a new directory. Existing packages cannot be silently overwritten.
    fs::create_dir(output).map_err(|_| "mission_output_must_be_new")?;
    let candidate = output.join("candidate");
    fs::create_dir(&candidate).map_err(|_| "cannot_create_mission_candidate")?;
    fs::create_dir(candidate.join("documents")).map_err(|_| "cannot_create_mission_documents")?;
    let mut ids = p.selected.clone();
    ids.sort();
    let meta = mission::metadata();
    let mut records = Vec::new();
    for id in &ids {
        let source = mission::source(id).ok_or("mission_document_not_allowed")?;
        fs::write(
            candidate.join("documents").join(format!("{id}.txt")),
            source.as_bytes(),
        )
        .map_err(|_| "cannot_write_mission_document")?;
        records.push(
            meta["records"]
                .as_array()
                .unwrap()
                .iter()
                .find(|v| v["id"] == *id)
                .unwrap()
                .clone(),
        );
    }
    let manifest = json!({"format":"rai-offline-pack-v1","execution_location":"host","request_version":r.request_version,"catalog_version":1,"permissions_version":1,"goal":r.goal,"records":records});
    fs::write(
        candidate.join("manifest.json"),
        serde_json::to_string_pretty(&manifest).map_err(|_| "cannot_encode_manifest")? + "\n",
    )
    .map_err(|_| "cannot_write_manifest")?;
    fs::write(
        candidate.join("plan.json"),
        serde_json::to_string_pretty(&p).map_err(|_| "cannot_encode_mission_plan")? + "\n",
    )
    .map_err(|_| "cannot_write_mission_plan")?;
    fs::write(candidate.join("index.html"), reader(&p))
        .map_err(|_| "cannot_write_offline_reader")?;
    // Fixed independent checker: never model-selected code/path/arguments.
    // Candidate remains inspectable on failure; published never contains partial work.
    let verdict = Command::new("python3")
        .args(["-B", "scripts/check_offline_pack.py"])
        .arg(&candidate)
        .env_remove("MODEL_API_KEY")
        .output()
        .map_err(|_| "cannot_start_mission_checker")?;
    println!(
        "{}",
        json!({"event":"mission_independent_check","passed":verdict.status.success(),"execution_location":"host"})
    );
    if !verdict.status.success() {
        return Err("mission_independent_check_failed".into());
    }
    fs::rename(&candidate, output.join("published")).map_err(|_| "cannot_publish_mission")?;
    println!(
        "{}",
        json!({"event":"mission_published","directory":output.join("published"),"documents":ids,"execution_location":"host","guest_execution":false,"pending_actions":p.pending.len()})
    );
    Ok(())
}
